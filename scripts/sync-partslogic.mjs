#!/usr/bin/env node
// Copies PartsLogic's shared code into src/vendor/partslogic/, byte for byte, from one commit.
//
// PartsLogic is the source of truth for the database wrappers (packages/shared) and the generated
// database types (packages/db-types). This app never edits those copies: change them in PartsLogic,
// then run this script again. SOURCE.json records the commit the copy came from.
//
// Usage:
//   node scripts/sync-partslogic.mjs --from ../PartsLogic --ref main
//   PARTSLOGIC_DIR=../PartsLogic node scripts/sync-partslogic.mjs --ref 5c888ee

import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'src', 'vendor', 'partslogic');

// What is copied, as [source folder or file in PartsLogic, destination under src/vendor/partslogic].
const SOURCES = [
  ['packages/shared/src', 'shared'],
  ['packages/db-types/src/database.ts', 'db-types/database.ts'],
];

function option(name, fallback) {
  const index = process.argv.indexOf(`--${name}`);
  return index > -1 ? process.argv[index + 1] : fallback;
}

const from = path.resolve(option('from', process.env.PARTSLOGIC_DIR ?? path.join(root, '..', 'PartsLogic')));
const ref = option('ref', 'main');

const git = (...args) => execFileSync('git', ['-C', from, ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

let commit;
try {
  commit = git('rev-parse', '--verify', `${ref}^{commit}`).trim();
} catch {
  console.error(`Could not find "${ref}" in ${from}. Clone PartsLogic there (or pass --from) and fetch the ref.`);
  process.exit(1);
}

// Files at that commit, so the copy never includes uncommitted work.
const files = SOURCES.flatMap(([source, destination]) => {
  const listed = git('ls-tree', '-r', '--name-only', commit, '--', source).split('\n').filter(Boolean);
  if (listed.length === 0) {
    console.error(`${source} does not exist at ${commit}.`);
    process.exit(1);
  }
  return listed.map((file) => ({
    source: file,
    destination: path.join(destination, listed.length === 1 && file === source ? '' : path.relative(source, file)),
  }));
});

rmSync(target, { recursive: true, force: true });
for (const file of files) {
  const out = path.join(target, file.destination);
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, git('show', `${commit}:${file.source}`));
}

writeFileSync(
  path.join(target, 'SOURCE.json'),
  `${JSON.stringify(
    {
      note: 'Generated by scripts/sync-partslogic.mjs. Do not edit these files; change PartsLogic and sync again.',
      // A fixed name, not the git remote: a local remote URL can carry a token.
      repository: 'SaabirStacks/PartsLogic',
      ref,
      commit,
      files: files.map((file) => ({ from: file.source, to: file.destination })),
    },
    null,
    2,
  )}\n`,
);

console.log(`Copied ${files.length} files from ${ref} (${commit.slice(0, 7)}) into src/vendor/partslogic.`);
